import { getDb } from './db.js'
import { stripSyntheticBlocks } from './preview.js'
import { getRateLimitSnapshot } from './ratelimit.js'

const MINUTE_MS = 60_000
const HOUR_MS = 3_600_000
const MINUTES_KEPT = 60
const HOURS_KEPT = 24
const RETENTION_DAYS = 30
const RECENT_LIMIT = 50

export interface RequestRecord {
  ts: number
  client: string
  method: string
  path: string
  status: number
  durationMs: number
  model?: string
  inputTokens?: number
  outputTokens?: number
  cacheReadTokens?: number
  cacheCreationTokens?: number
  costUsd?: number
  // Truncated last user message text — for at-a-glance dashboard display
  userMessage?: string
  // Where a >=400 response originated: 'gateway' (generated by this proxy) or
  // 'upstream' (relayed from the Claude API). Empty for successes.
  errorSource?: 'gateway' | 'upstream' | ''
  // Short decoded error payload (e.g. Anthropic's error type + message).
  errorDetail?: string
}

let startedAt = Date.now()
let cleanupTimer: NodeJS.Timeout | null = null

export function initMetrics() {
  startedAt = Date.now()
  pruneOldRows()
  if (cleanupTimer) clearInterval(cleanupTimer)
  cleanupTimer = setInterval(pruneOldRows, HOUR_MS).unref()
}

function pruneOldRows() {
  const cutoff = Date.now() - RETENTION_DAYS * 24 * HOUR_MS
  try {
    getDb().prepare('DELETE FROM request_metrics WHERE ts < ?').run(cutoff)
  } catch {
    // DB may not be initialized yet during early startup
  }
}

export function recordRequest(rec: RequestRecord) {
  try {
    getDb()
      .prepare(
        `INSERT INTO request_metrics (
          ts, client, method, path, status, duration_ms,
          model, input_tokens, output_tokens,
          cache_read_tokens, cache_creation_tokens, cost_usd,
          user_message, error_source, error_detail
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      )
      .run(
        rec.ts, rec.client, rec.method, rec.path, rec.status, rec.durationMs,
        rec.model || '',
        rec.inputTokens || 0,
        rec.outputTokens || 0,
        rec.cacheReadTokens || 0,
        rec.cacheCreationTokens || 0,
        rec.costUsd || 0,
        rec.userMessage || '',
        rec.errorSource || '',
        rec.errorDetail || '',
      )
  } catch (err) {
    // Don't break proxying on metrics failures
  }
}

/**
 * Sum of cost_usd for a client since the given timestamp.
 * sinceTs = 0 means lifetime.
 */
export function getClientCostSince(client: string, sinceTs: number): number {
  try {
    const row = getDb()
      .prepare(
        'SELECT SUM(cost_usd) as cost FROM request_metrics WHERE client = ? AND ts >= ?',
      )
      .get(client, sinceTs) as { cost: number | null }
    return row?.cost || 0
  } catch {
    return 0
  }
}

/**
 * Resolve the start-of-window timestamp for a cost-limit period.
 * UTC-based for stability across server timezones.
 */
export function periodStart(period: 'lifetime' | 'monthly' | 'daily' | undefined): number {
  const now = new Date()
  if (period === 'daily') {
    return Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate())
  }
  if (period === 'monthly') {
    return Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1)
  }
  return 0
}

/**
 * Per-client usage summary for the self-service portal: lifetime totals plus
 * today / 7d / 30d breakdowns. Scoped to a single client so a portal user only
 * ever sees their own numbers.
 */
export function getClientStats(client: string) {
  const db = getDb()
  const now = Date.now()

  const totalsRow = db
    .prepare(
      `SELECT
        COUNT(*) as total,
        SUM(CASE WHEN status >= 400 THEN 1 ELSE 0 END) as errors,
        SUM(input_tokens) as input_tokens,
        SUM(output_tokens) as output_tokens,
        SUM(cache_read_tokens) as cache_read_tokens,
        SUM(cache_creation_tokens) as cache_creation_tokens,
        SUM(cost_usd) as cost_usd,
        MAX(ts) as last_seen
      FROM request_metrics WHERE client = ?`,
    )
    .get(client) as {
      total: number
      errors: number | null
      input_tokens: number | null
      output_tokens: number | null
      cache_read_tokens: number | null
      cache_creation_tokens: number | null
      cost_usd: number | null
      last_seen: number | null
    }

  const day = 24 * HOUR_MS
  const periodDefs = [
    { key: 'today', label: 'Today', since: now - day },
    { key: '7d', label: 'Last 7d', since: now - 7 * day },
    { key: '30d', label: 'Last 30d', since: now - 30 * day },
  ]
  const periodStmt = db.prepare(
    `SELECT
      COUNT(*) as total,
      SUM(input_tokens) as input_tokens,
      SUM(output_tokens) as output_tokens,
      SUM(cache_read_tokens) as cache_read_tokens,
      SUM(cache_creation_tokens) as cache_creation_tokens,
      SUM(cost_usd) as cost_usd
    FROM request_metrics WHERE client = ? AND ts >= ?`,
  )
  const periods = periodDefs.map((p) => {
    const r = periodStmt.get(client, p.since) as {
      total: number
      input_tokens: number | null
      output_tokens: number | null
      cache_read_tokens: number | null
      cache_creation_tokens: number | null
      cost_usd: number | null
    }
    return {
      key: p.key,
      label: p.label,
      total: r.total || 0,
      inputTokens: r.input_tokens || 0,
      outputTokens: r.output_tokens || 0,
      cacheReadTokens: r.cache_read_tokens || 0,
      cacheCreationTokens: r.cache_creation_tokens || 0,
      costUsd: r.cost_usd || 0,
    }
  })

  return {
    lifetime: {
      total: totalsRow.total || 0,
      errors: totalsRow.errors || 0,
      inputTokens: totalsRow.input_tokens || 0,
      outputTokens: totalsRow.output_tokens || 0,
      cacheReadTokens: totalsRow.cache_read_tokens || 0,
      cacheCreationTokens: totalsRow.cache_creation_tokens || 0,
      costUsd: totalsRow.cost_usd || 0,
      lastSeen: totalsRow.last_seen || 0,
    },
    periods,
  }
}

/** Per-model usage totals scoped to a single client (for the portal). */
export function getClientModels(client: string) {
  const rows = getDb()
    .prepare(
      `SELECT
        model,
        COUNT(*) as total,
        SUM(input_tokens) as input_tokens,
        SUM(output_tokens) as output_tokens,
        SUM(cache_read_tokens) as cache_read_tokens,
        SUM(cache_creation_tokens) as cache_creation_tokens,
        SUM(cost_usd) as cost_usd
      FROM request_metrics
      WHERE client = ? AND model != ''
      GROUP BY model
      ORDER BY cost_usd DESC`,
    )
    .all(client) as Array<{
      model: string
      total: number
      input_tokens: number | null
      output_tokens: number | null
      cache_read_tokens: number | null
      cache_creation_tokens: number | null
      cost_usd: number | null
    }>
  return rows.map((r) => ({
    model: r.model,
    total: r.total,
    inputTokens: r.input_tokens || 0,
    outputTokens: r.output_tokens || 0,
    cacheReadTokens: r.cache_read_tokens || 0,
    cacheCreationTokens: r.cache_creation_tokens || 0,
    costUsd: r.cost_usd || 0,
  }))
}

/** Most recent requests for a single client (for the portal activity feed). */
export function getClientRecent(client: string, limit = 20) {
  const rows = getDb()
    .prepare(
      `SELECT
        ts, method, path, status,
        duration_ms as durationMs,
        model,
        input_tokens as inputTokens,
        output_tokens as outputTokens,
        cache_read_tokens as cacheReadTokens,
        cache_creation_tokens as cacheCreationTokens,
        cost_usd as costUsd,
        user_message as userMessage,
        error_source as errorSource,
        error_detail as errorDetail
      FROM request_metrics
      WHERE client = ?
      ORDER BY ts DESC
      LIMIT ?`,
    )
    .all(client, limit) as Array<RequestRecord>
  return rows.map((r) => r.userMessage
    ? { ...r, userMessage: stripSyntheticBlocks(r.userMessage) }
    : r)
}

